// Bakes every class's skill groups (skill id → the groups Ark Grid core effects name) from the Maxroll feed cache
// (cache/maxroll-skills.json) and scripts/skill-group-map.mjs into src/lib/upgrade-planner/skill-groups.ts.
//   node scripts/bake-skill-groups.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { CATEGORY_GROUPS, CLASS_TYPE_GROUPS, TYPE_GROUPS } from './skill-group-map.mjs';

const skills = JSON.parse(readFileSync('cache/maxroll-skills.json', 'utf8'));
const groups = {};
for (const [id, k] of Object.entries(skills)) {
	if (!k?.class) continue;
	const names = [
		...Object.entries(CATEGORY_GROUPS[k.class] ?? {}).filter(([, cats]) => cats.includes(k.category)).map(([name]) => name),
		...Object.entries({ ...TYPE_GROUPS, ...CLASS_TYPE_GROUPS[k.class] }).filter(([, type]) => type === k.type).map(([name]) => name)
	];
	if (names.length) (groups[k.class] ??= {})[id] = names;
}

// Souleater was listed by hand and confirmed by a Souleater player (10-19-26): the data must agree.
const confirmed = { Stygian: [46430, 46410, 46450, 46400, 46440, 46420], Ghast: [46650, 46240, 46200, 46250, 46210, 46220, 46230], Deathlord: [46510, 46640, 46520, 46500, 46530] };
for (const [name, ids] of Object.entries(confirmed))
	for (const id of ids) if (!groups.souleater?.[id]?.includes(name)) throw new Error(`Souleater ${id} should be ${name}`);

writeFileSync('src/lib/upgrade-planner/skill-groups.ts', `// Generated by scripts/bake-skill-groups.mjs. Do not edit by hand.
// Which skill groups each class skill belongs to, for Ark Grid core effects like "Stygian Skill Damage +0.6%" or
// "Holding Skill Damage +x%": the game's skill category and type (Maxroll feed), named per scripts/skill-group-map.mjs
// (lostarkcodex.com tags). Souleater's are checked against the hand list a Souleater player confirmed (10-19-26).

/** Class → skill id → groups ("Stygian", "Holding"). */
export const SKILL_GROUPS: Record<string, Record<number, string[]>> = ${JSON.stringify(groups)};
`);
console.log(Object.keys(groups).length, 'classes,', Object.values(groups).reduce((n, g) => n + Object.keys(g).length, 0), 'skills');
