// Game facts from LOA Logs' extracted NPC table; only bosses named in our raid map are shipped.
// node scripts/bake-boss-species.mjs [path/to/Npc.json]
import fs from 'node:fs';
import ts from 'typescript';

const source = 'https://raw.githubusercontent.com/snoww/loa-logs/master/src-tauri/meter-data/Npc.json';
const file = process.argv[2] ?? 'cache/meter-npc.json';
if (!fs.existsSync(file)) {
	const response = await fetch(source);
	if (!response.ok) throw new Error(`Npc.json: ${response.status}`);
	fs.mkdirSync('cache', { recursive: true });
	fs.writeFileSync(file, await response.text());
}
const npcs = Object.values(JSON.parse(fs.readFileSync(file, 'utf8')));
const raids = ts.createSourceFile('raids.ts', fs.readFileSync('src/lib/logs/raids.ts', 'utf8'), ts.ScriptTarget.Latest, true);
const declaration = raids.statements.filter(ts.isVariableStatement).flatMap(s => [...s.declarationList.declarations])
	.find(d => d.name.getText(raids) === 'RAIDS')?.initializer;
if (!declaration || !ts.isArrayLiteralExpression(declaration)) throw new Error('RAIDS array not found');
const names = declaration.elements.flatMap(raid => [...raid.elements[1].elements]
	.flatMap(gate => [...gate.elements].map(boss => boss.text)));
const rank = { commander: 4, raid: 3, epic_raid: 2, boss: 1 };
const data = {};
for (const name of names) {
	const matches = npcs.filter(n => n.name === name && rank[n.grade]);
	const highest = Math.max(...matches.map(n => rank[n.grade]));
	// Lower-grade copies share names with commanders. Conflicting classifications at the same grade stay unknown.
	const species = [...new Set(matches.filter(n => rank[n.grade] === highest).map(n => n.species))];
	if (species.length === 1 && species[0] && species[0] !== 'none') data[name] = species[0];
}
fs.writeFileSync('src/lib/logs/boss-species-data.ts', `// Generated by scripts/bake-boss-species.mjs. Game NPC species via LOA Logs' Npc.json.
// Source: ${source}
// Highest raid grade per name; ambiguous / missing species omitted.
export const BOSS_SPECIES: Readonly<Record<string, string>> = ${JSON.stringify(data, null, '\t')};
`);
console.log(`${Object.keys(data).length} boss classifications`);
