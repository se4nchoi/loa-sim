// Bakes what the DPS meter reads off a dealer's Ark Grid besides Order cores into
// src/lib/upgrade-planner/dealer-grid.ts, from the Maxroll feed cache (cache/maxroll-items.json, cache/maxroll-stats.json):
//   - chaos cores' lines by core item id and points, as stats: Damage to foes, On Crit Hit damage, Damage to Boss,
//     Additional Damage, Crit Rate / Damage, Atk. Power and Weapon Power (flat and %). A line with no damage stat the
//     meter can scale (Atk. Speed, cooldowns, Burn, Weak Point, debuffs on the target) is kept as text, unvalued;
//   - the dealer astrogem options' stat value per total level (2001 Atk. Power %, 2002 Additional Damage, 2003 Damage to
//     Boss; hundredths of a percent).
//   node scripts/bake-dealer-grid.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const items = JSON.parse(readFileSync('cache/maxroll-items.json', 'utf8'));
const stats = JSON.parse(readFileSync('cache/maxroll-stats.json', 'utf8'));
const strip = (s) => (s ?? '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
const num = (s) => Number(String(s).replace(/,/g, ''));

/** One option's text → its stats, and what's left that the meter can't value. */
function linesOf(text) {
	const out = {};
	const add = (k, v) => (out[k] = (out[k] ?? 0) + v);
	let rest = text;
	const take = (re, fn) => { rest = rest.replace(re, (...m) => { fn(m); return ''; }); };
	take(/On Crit Hit, Damage to foes \+([\d.]+)%\.?/g, (m) => add('critHit', num(m[1])));
	take(/Damage to Boss or higher foes \+([\d.]+)%\.?/g, (m) => add('boss', num(m[1])));
	take(/Damage to foes \+([\d.]+)%\.?/g, (m) => add('damage', num(m[1])));
	take(/Additional Damage \+([\d.]+)%\.?/g, (m) => add('addDmg', num(m[1])));
	take(/Crit Rate \+([\d.]+)%\.?/g, (m) => add('critRate', num(m[1])));
	take(/(?<!target takes \+[\d.]+% )Crit Damage \+([\d.]+)%\.?/g, (m) => add('critDamage', num(m[1])));
	take(/Atk\. Power \+([\d.]+)% and \+([\d,]+)\.?/g, (m) => { add('atkPct', num(m[1])); add('atkFlat', num(m[2])); });
	take(/Atk\. Power \+([\d.]+)%\.?/g, (m) => add('atkPct', num(m[1])));
	take(/Atk\. Power \+([\d,]+)\.?/g, (m) => add('atkFlat', num(m[1])));
	take(/Weapon Power \+([\d.]+)% and \+([\d,]+)\.?/g, (m) => { add('wpPct', num(m[1])); add('wpFlat', num(m[2])); });
	take(/Weapon Power \+([\d.]+)%\.?/g, (m) => add('wpPct', num(m[1])));
	take(/Weapon Power \+([\d,]+)\.?/g, (m) => add('wpFlat', num(m[1])));
	rest = rest.replace(/\s+/g, ' ').trim();
	// What's left only matters for damage when it names one of these; defense, HP, MP and ally lines don't.
	if (/Atk\. Speed|Skill Cooldown|Burn|Weak Point|takes \+|Damage from/.test(rest)) out.unvalued = rest;
	return out;
}

const chaos = {};
for (const [id, item] of Object.entries(items)) {
	const core = item?.arkCore;
	if (!core || core.attr !== 1) continue;
	const lines = core.bonuses.map((b) => ({ points: b.points, ...linesOf(strip(stats.arkGridCoreOptions[b.id]?.desc)) }))
		.filter((l) => Object.keys(l).length > 1);
	if (lines.length) chaos[id] = lines;
}

const options = stats.arkGridGemOptions;
const astrogems = {};
for (const id of [2001, 2002, 2003]) {
	const values = [];
	for (let level = 1; options[`${id}#${level}`]; level++) values.push(options[`${id}#${level}`].stat?.value || options[`${id}#${level}`].value || 0);
	astrogems[id] = values;
}

writeFileSync('src/lib/upgrade-planner/dealer-grid.ts', `// Generated by scripts/bake-dealer-grid.mjs from the Maxroll feed. Do not edit by hand.
/**
 * A chaos core line from \`points\`: Damage to foes, On Crit Hit damage, Damage to Boss, Additional Damage, Crit Rate,
 * Crit Damage, Atk. Power % / flat, Weapon Power % / flat (percent values in percent); \`unvalued\`: text with no damage
 * stat to scale (Atk. Speed, cooldowns, Burn, Weak Point, debuffs).
 */
export interface ChaosCoreLine {
	points: number; damage?: number; critHit?: number; boss?: number; addDmg?: number; critRate?: number; critDamage?: number;
	atkPct?: number; atkFlat?: number; wpPct?: number; wpFlat?: number; unvalued?: string;
}
export const CHAOS_CORE_LINES: Record<number, ChaosCoreLine[]> = ${JSON.stringify(chaos)};

/** Dealer astrogem options: stat value (hundredths of a percent) at each total level from 1: 2001 Atk. Power %, 2002 Additional Damage, 2003 Damage to Boss. */
export const DEALER_ASTROGEM_VALUES: Record<number, number[]> = ${JSON.stringify(astrogems)};
`);
