// Bakes what the support sim reads off the Ark Grid into src/lib/upgrade-planner/support-buffs.ts:
//   - the support astrogem options' stat value per total level (Ally Damage Enhancement, Brand Power, Ally Atk. Power
//     Enhancement; hundredths of a percent, like accessory lines), from the Maxroll feed cache (cache/maxroll-stats.json).
//     The CP tables hold battle points, not these values;
//   - support Order cores' Ally Atk. Power / Ally Damage Enhancement lines by core id and points, from
//     src/lib/upgrade-planner/order-cores.ts (bake-order-cores.mjs): for every buff, or one skill's buffs ("Paint: Dragon
//     Engraving's Party Damage Enhancement"), always or while a Destiny effect is up ("Destiny: Sun's Embrace: …").
//   node scripts/bake-support-buffs.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const options = JSON.parse(readFileSync('cache/maxroll-stats.json', 'utf8')).arkGridGemOptions;
const astrogems = {};
for (const id of [2011, 2012, 2013]) {
	const values = [];
	for (let level = 1; options[`${id}#${level}`]; level++) values.push(options[`${id}#${level}`].stat.value);
	astrogems[id] = values;
}

const src = readFileSync('src/lib/upgrade-planner/order-cores.ts', 'utf8').split('\n');
const grab = (name) => JSON.parse(src.find((l) => l.startsWith(`export const ${name}`)).replace(/^[^=]*= /, '').replace(/;$/, ''));
const cores = grab('ORDER_CORES'), effects = grab('ORDER_CORE_EFFECTS');
const SUPPORTS = new Set(['bard', 'holyknight', 'holyknight_female', 'yinyangshi']);

/** One line: which stat, how much, and when / on what: { points, stat, pct, skill?, destiny? }; null when it's none. */
function lineOf(points, raw) {
	let text = raw.replace(/\s+/g, ' ').trim();
	let destiny;
	const d = text.match(/^(?:On Destiny (?:activation|use), gain the Destiny: [^.]+? for [\d.]+s\. )?(Destiny: [^:]+): (.*)$/);
	if (d) {
		destiny = d[1].trim();
		text = d[2].replace(/^Effect is enhanced\. /, '');
	}
	const at = (stat, pct, skill) => ({ points, stat, pct: Number(pct), ...(skill ? { skill } : {}), ...(destiny ? { destiny } : {}) });
	let m;
	if ((m = text.match(/^(?:Party|Ally) (?:Atk\.|Attack\.?) Power Enhancement(?: [Ee]ffect)? \+([\d.]+)%\.?$/))) return at('atk', m[1]);
	if ((m = text.match(/^(?:Party|Ally) Damage Enhancement [Ee]ffect \+([\d.]+)%\.?$/))) return at('dmg', m[1]);
	if ((m = text.match(/^(?:Party|Ally) Damage Enhancement [Ee]ffect of (.+?) \+([\d.]+)%\.?$/))) return at('dmg', m[2], m[1]);
	if ((m = text.match(/^(.+?)(?:'s)? (?:Party|Ally) Damage Enhancement [Ee]ffect \+([\d.]+)%\.?$/))) return at('dmg', m[2], m[1]);
	return null;
}

const coreLines = {};
const unread = new Set();
for (const [id, c] of Object.entries(cores)) {
	if (!SUPPORTS.has(c.cls)) continue;
	const lines = [];
	for (const [points, option] of c.bonuses) {
		const text = (effects[option] ?? []).map((e) => e.text ?? '').join(' ').trim();
		if (!/Enhancement/.test(text)) continue;
		const line = lineOf(points, text);
		if (line) lines.push(line);
		else unread.add(text);
	}
	if (lines.length) coreLines[id] = lines;
}
if (unread.size) console.log('not read:\n  ' + [...unread].join('\n  '));

// Support chaos cores (Faith / Fortitude Enhancement, Echoing Brand): their Ally Atk. Power / Ally Damage Enhancement and
// Brand Power lines, and Echoing Brand's "target takes +x% Damage from you and party members" (a buff the logs keep).
const items = JSON.parse(readFileSync('cache/maxroll-items.json', 'utf8'));
const coreOptions = JSON.parse(readFileSync('cache/maxroll-stats.json', 'utf8')).arkGridCoreOptions;
const strip = (s) => (s ?? '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
const chaosLines = {};
for (const [id, item] of Object.entries(items)) {
	const core = item?.arkCore;
	if (!core || core.attr !== 1) continue;
	const lines = [];
	for (const b of core.bonuses) {
		const text = strip(coreOptions[b.id]?.desc);
		const num = (re) => Number(text.match(re)?.[1] ?? 0);
		const line = { points: b.points, allyAtk: num(/Ally Atk\. Power Enhancement effect \+([\d.]+)%/), allyDmg: num(/Ally Damage Enhancement effect \+([\d.]+)%/),
			brand: num(/Brand Power \+([\d.]+)%/), takenDmg: num(/target takes \+([\d.]+)% Damage from you and party members/) };
		const kept = Object.fromEntries(Object.entries(line).filter(([k, v]) => k === 'points' || v));
		if (Object.keys(kept).length > 1) lines.push(kept);
	}
	if (lines.length) chaosLines[id] = lines;
}

writeFileSync('src/lib/upgrade-planner/support-buffs.ts', `// Generated by scripts/bake-support-buffs.mjs. Do not edit by hand.
// Support astrogem options: stat value (hundredths of a percent) at each total level from 1, by option id:
// 2011 Ally Damage Enhancement, 2012 Brand Power, 2013 Ally Atk. Power Enhancement.
export const SUPPORT_ASTROGEM_VALUES: Record<number, number[]> = ${JSON.stringify(astrogems)};

/**
 * A support Order core's enhancement line: from \`points\`, Ally Atk. Power ('atk') or Ally Damage ('dmg') Enhancement
 * +\`pct\` percent, for every buff or only the buffs of \`skill\` (its name), always or while the \`destiny\` effect is up.
 */
export interface SupportCoreLine { points: number; stat: 'atk' | 'dmg'; pct: number; skill?: string; destiny?: string }
export const SUPPORT_CORE_LINES: Record<number, SupportCoreLine[]> = ${JSON.stringify(coreLines)};

/**
 * A support chaos core's line from \`points\`: Ally Atk. Power / Ally Damage Enhancement and Brand Power (percent), and
 * \`takenDmg\`: Echoing Brand's "target takes +x% Damage from you and party members" while the Brand is up.
 */
export interface SupportChaosLine { points: number; allyAtk?: number; allyDmg?: number; brand?: number; takenDmg?: number }
export const SUPPORT_CHAOS_LINES: Record<number, SupportChaosLine[]> = ${JSON.stringify(chaosLines)};
`);
console.log(Object.keys(chaosLines).length, 'chaos cores with support lines');
const all = Object.values(coreLines).flat();
console.log(Object.keys(coreLines).length, 'cores;', all.filter((l) => !l.skill && !l.destiny).length, 'plain,', all.filter((l) => l.skill).length, 'skill,', all.filter((l) => l.destiny).length, 'destiny lines');
console.log('skills named:', [...new Set(all.map((l) => l.skill).filter(Boolean))].join(' | '));
console.log('destinies:', [...new Set(all.map((l) => l.destiny).filter(Boolean))].join(' | '));
