// Generate only the honing book slice (Hellfire for Aegir, Tremor for Serca), without regenerating unrelated game data.
// node --use-env-proxy scripts/bake-honing-books.mjs [stats.json items.json]
import fs from 'node:fs';
const base = 'https://assets-ng.maxroll.gg/laplanner/game/';
async function read(name, path) {
 if (path) return JSON.parse(fs.readFileSync(path, 'utf8'));
 const response = await fetch(`${base}${name}.json`);
 if (!response.ok) throw new Error(`${name}: ${response.status}`);
 return response.json();
}
const stats = await read('stats', process.argv[2]);
const items = await read('items', process.argv[3]);
// canonical market id, bound equivalent, slot, eligible targets
const specs = [
 ['66112543','66112651','weapon',11,14], ['66112546','66112652','armor',11,14],
 ['66112551','66112653','weapon',15,18], ['66112552','66112654','armor',15,18],
 ['66112553','66112655','weapon',19,20], ['66112554','66112656','armor',19,20],
 ['66112555','66112657','weapon',19,20], ['66112556','66112658','armor',19,20]
];
const books = specs.map(([id, boundId, kind, from, to]) => {
 // The current feed omits metadata for 66112543, but links it in enhanceMaterial.
 // Its bound equivalent supplies the identical name, icon and printed rates.
 const item = items[id] ?? items[boundId];
 if (!item?.name.includes('Hellfire')) throw new Error(`Missing Hellfire item ${id}`);
 const rates = {};
 for(let level = from; level <= to; level++) {
  const rows = stats.enhanceMaterial[`${kind === 'weapon' ? '41050' : '41051'}${level}`];
  const market = rows?.find(row => String(row.id) === id);
  const bound = rows?.find(row => String(row.id) === boundId);
  const rate = market?.effects.find(effect => effect.type === 1)?.value;
  if (!(rate > 0) || bound?.effects.find(effect => effect.type === 1)?.value !== rate) throw new Error(`Missing/mismatched book rate ${id} +${level}`);
  const printed = item.desc.match(new RegExp(`Honing Lv\\. ${level} \\([^)]*\\): \\+([\\d.]+)%`));
  if (!printed || Number(printed[1]) * 100 !== rate) throw new Error(`Description disagrees for ${id} +${level}`);
  rates[level] = rate;
 }
 return { id, name: item.name.replace(/ \(Bound\)$/, ''), icon: item.icon, set: 'aegir', kind, rates };
});
// Serca's Tremor books (Arbiter of Death, 2026-10-21) are not in Maxroll's feed yet, so they have no game ids:
// keyed by name until a feed lists them. Each book adds the target level's base success rate, the same rule the
// Hellfire rows above verify against Aegir's base rates; Serca bases: +12/13 5%, +14-16 4%, +17-19 3%.
// Names and ranges: https://www.playlostark.com/en-us/game/releases/arbiter-of-death
// Tremor artwork (both ranges), verified against the item images at https://loaup.com/:
// https://cdn-lostark.game.onstove.com/efui_iconatlas/use/use_12_218.png (Metallurgy)
// https://cdn-lostark.game.onstove.com/efui_iconatlas/use/use_12_219.png (Tailoring)
const tremor = (kind, from, to, rates) => ({ id: `tremor:${kind}:${from}-${to}`, name: `${kind === 'weapon' ? 'Metallurgy' : 'Tailoring'}: Tremor [${from}-${to}]`,
 icon: kind === 'weapon' ? 'Use_12_218' : 'Use_12_219', set: 'serca', kind, rates });
const low = { 12: 500, 13: 500, 14: 400, 15: 400 }, high = { 16: 400, 17: 300, 18: 300, 19: 300 };
books.push(tremor('weapon', 12, 15, low), tremor('armor', 12, 15, low), tremor('weapon', 16, 19, high), tremor('armor', 16, 19, high));
const output = `// Generated by scripts/bake-honing-books.mjs from Maxroll's items + enhanceMaterial tables.\n// Source: ${base}{items,stats}.json; Serca Tremor rows are sourced in the script (not in the feed yet).\n// Rates are additive percentage points in 1/10000 units, keyed by target honing level.\nexport interface HoningBookData {\n id: string; name: string; icon: string; set: 'aegir' | 'serca';\n kind: 'weapon' | 'armor'; rates: Record<number, number>;\n}\nexport const HONING_BOOKS: HoningBookData[] = ${JSON.stringify(books,null,'\t')};\n`;
fs.writeFileSync('src/lib/upgrade-planner/honing-books-data.ts', output);
console.log(`Generated ${books.length} honing book rows (Hellfire verified against the feed).`);
