// Bakes the support astrogem options' stat value per total level (Ally Damage Enhancement, Brand Power, Ally Atk. Power
// Enhancement; hundredths of a percent, like accessory lines) from the Maxroll feed cache (cache/maxroll-stats.json)
// into src/lib/upgrade-planner/support-astrogems.ts. The CP tables hold battle points, not these values.
//   node scripts/bake-support-astrogems.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const options = JSON.parse(readFileSync('cache/maxroll-stats.json', 'utf8')).arkGridGemOptions;
const table = {};
for (const id of [2011, 2012, 2013]) {
	const values = [];
	for (let level = 1; options[`${id}#${level}`]; level++) values.push(options[`${id}#${level}`].stat.value);
	table[id] = values;
}
writeFileSync('src/lib/upgrade-planner/support-astrogems.ts', `// Generated by scripts/bake-support-astrogems.mjs from the Maxroll feed. Do not edit by hand.
// Support astrogem options: stat value (hundredths of a percent) at each total level from 1, by option id:
// 2011 Ally Damage Enhancement, 2012 Brand Power, 2013 Ally Atk. Power Enhancement.
export const SUPPORT_ASTROGEM_VALUES: Record<number, number[]> = ${JSON.stringify(table)};
`);
console.log(Object.entries(table).map(([id, v]) => `${id}: ${v.length} levels, max ${v.at(-1)}`).join('; '));
