// Reuses the cached game tables fetched by bake-game-data.mjs.
import fs from 'node:fs';
const stats = JSON.parse(fs.readFileSync('cache/maxroll-stats.json', 'utf8'));
const option = (id) => stats.itemRandom[`${id}#6`][0].subgroups[0].options[0];
const curves = Object.fromEntries([['weapon', 10144000], ['armor', 10144001]].map(([name, id]) => {
 const row = option(id);
 return [name, { max: row.stats[0].value, deviation: row.deviation, exponent: row.amplify }];
}));
const hp = Object.fromEntries(Object.values(stats.classes).filter((c) => c.actionObject && c.hpCon).map((c) => [c.actionObject.replaceAll('_', '').toLowerCase(), c.hpCon]));
fs.writeFileSync('src/lib/upgrade-planner/quality-data.ts', `// Generated by scripts/bake-quality-data.mjs from game tables via Maxroll's planner feed.\nexport const QUALITY_CURVES = ${JSON.stringify(curves)};\nexport const CLASS_HP_COEFFICIENT: Record<string, number> = ${JSON.stringify(hp)};\n`);
