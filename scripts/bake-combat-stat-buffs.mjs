// Numeric game facts used by the compact hit-window importer. node scripts/bake-combat-stat-buffs.mjs
import fs from 'node:fs';
const table = JSON.parse(fs.readFileSync('cache/meter-skillbuff.json', 'utf8'));
const combat = JSON.parse(fs.readFileSync('cache/meter-combat-effect.json', 'utf8'));
// These leave the primary AP/CD buckets unchanged on a recorded hit. Triggered casts remain recorded, not added.
const fixed = new Set(['modify_damage', 'modify_damage_when_critical', 'modify_damage_shield_multiplier',
	'modify_paralyzation_point', 'modify_reactive_damage', 'modify_critical_ratio', 'modify_evolution_damage_multiplier',
	'exec_start_skill', 'exec_reactive_effect_when_damage', 'exec_when_counter', 'exec_after_effect', 'exec_active_effect_when_damage', 'exec_after_skill']);
const relevant = {};
for (const [id, buff] of Object.entries(table)) {
	const levels = Object.values(buff.perLevelData ?? {});
	const primary = levels.map(level => {
		let ap = 0, cd = buff.type === 'instant_stat_amplify' ? (level.statusEffectValues?.[1] ?? 0) / 100 : 0;
		for (const option of level.passiveOptions ?? []) {
			if (['none', 'skill_group_cooldown_reduction', 'skill_cooldown_reduction'].includes(option.type)) continue;
			if (['combat_effect', 'ability_point'].includes(option.type)) {
				const actions = combat[option.keyIndex]?.effects?.flatMap(e => e.actions ?? []);
				if (!actions?.length || actions.some(a => !fixed.has(a.actionType) && a.actionType !== 'modify_critical_multiplier')) ap = cd = null;
				else if (actions.some(a => a.actionType === 'modify_critical_multiplier')) cd = null;
				continue;
			}
			if (option.type !== 'stat') { ap = cd = null; break; }
			if (option.keyStat === 'attack_power_rate' && ap !== null) ap += option.value / 100;
			if (option.keyStat === 'critical_dam_rate' && cd !== null) cd += option.value / 100;
		}
		return { ap, cd };
	});
	const unique = key => {
		const values = [...new Set(primary.map(value => value[key]))];
		return values.length === 1 ? values[0] : null;
	};
	const ap = unique('ap'), cd = unique('cd');
	if (ap !== 0 || cd !== 0 || buff.buffCategory === 'identity') relevant[id] = {
		ap, cd, ...(buff.overlap > 1 ? { stacks: buff.overlap } : {}),
		...(['Adrenaline', 'Ether Predator'].includes(buff.name) ? { fromGear: true } : {}),
		...(buff.buffCategory === 'identity' ? { state: true } : {})
	};
}
fs.writeFileSync('src/lib/logs/combat-stat-buffs.ts', `// Generated by scripts/bake-combat-stat-buffs.mjs from LOA Logs' extracted game SkillBuff.json.
// https://github.com/snoww/loa-logs/blob/master/src-tauri/meter-data/SkillBuff.json
export const KNOWN_STAT_BUFF_IDS: readonly number[] = ${JSON.stringify(Object.keys(table).map(Number))};
export const COMBAT_STAT_BUFFS: Readonly<Record<number, {ap: number | null; cd: number | null; stacks?: number; fromGear?: boolean; state?: boolean}>> = ${JSON.stringify(relevant)};
`);
console.log(`${Object.keys(table).length} known buffs, ${Object.keys(relevant).length} stat/state definitions`);
