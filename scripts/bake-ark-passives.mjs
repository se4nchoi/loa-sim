// Ark Passive node names (id → name, tree tier) from the Maxroll planner feed already cached by bake-game-data.mjs
// (cache/maxroll-stats.json). Used to say which build a clear was played with ("Full Moon Harvester").
// Run after bake-game-data.mjs: node scripts/bake-ark-passives.mjs
import fs from 'node:fs';

const stats = JSON.parse(fs.readFileSync('cache/maxroll-stats.json', 'utf8'));
const strip = (s) => String(s ?? '').replace(/<[^>]+>/g, '').trim();
const names = Object.fromEntries(
	Object.entries(stats.arkPassives)
		.filter(([, v]) => v.name)
		.map(([id, v]) => [id, [strip(v.name), v.tier ?? 0]])
);
const out = `// Generated by scripts/bake-ark-passives.mjs from the Maxroll planner feed. Do not edit.
/** Ark Passive node id → [name, tier within its tree (0 = first)]. */
export const ARK_PASSIVE_NODES: Record<string, [string, number]> = ${JSON.stringify(names)};
`;
fs.writeFileSync('src/lib/upgrade-planner/ark-passive-names.ts', out);
console.log(Object.keys(names).length, 'Ark Passive nodes');
