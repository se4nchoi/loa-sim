// Bakes the small slices of the game's tables the simulator needs, from Maxroll's planner data feed
// (https://assets-ng.maxroll.gg/laplanner/game/{stats,items,skills}.json). Run once per game patch:
//   node scripts/bake-game-data.mjs
// Writes:
//   src/lib/upgrade-planner/honing-data.ts  main stat / Weapon Power by honing level (T4 Aegir and Serca gear)
//   src/lib/upgrade-planner/game-data.ts    item icons + names, engraving icons, bracelet effect catalog,
//                                           gem-able class skills, gem skill effects by level

import fs from 'node:fs';

async function cached(name) {
	const file = `cache/maxroll-${name}.json`;
	if (!fs.existsSync(file)) {
		fs.mkdirSync('cache', { recursive: true });
		const res = await fetch(`https://assets-ng.maxroll.gg/laplanner/game/${name}.json`);
		if (!res.ok) throw new Error(`${name}.json: ${res.status}`);
		fs.writeFileSync(file, await res.text());
	}
	return JSON.parse(fs.readFileSync(file, 'utf8'));
}

const stats = await cached('stats');
const items = await cached('items');
const skills = await cached('skills');
const statOf = (list, stat) => (list ?? []).filter((s) => s.stat === stat).reduce((a, s) => a + s.value, 0);
const header = (what) => `// Generated by scripts/bake-game-data.mjs from the game's tables (via Maxroll's planner feed).
// Do not edit by hand. ${what}
`;

// ------------------------------------------------------------------------------------------- honing

const BASE_ILVL = 1675;
// levelOption ids (item table) and advanced-honing groups per slot; DEX variants, STR/INT are identical.
const SLOTS = {
	weapon: { levelOption: 12159000, amp: 1010, stat: 151 },
	head: { levelOption: 12159021, amp: 2110, stat: 4 },
	upper_body: { levelOption: 12159022, amp: 3110, stat: 4 },
	lower_body: { levelOption: 12159023, amp: 4110, stat: 4 },
	hand: { levelOption: 12159024, amp: 5110, stat: 4 },
	shoulder: { levelOption: 12159025, amp: 6110, stat: 4 }
};
function honingTable(baseIlvl, levelOffset) {
	const honing = {};
	for (const [slot, { levelOption, amp, stat }] of Object.entries(SLOTS)) {
		const h = Array.from({ length: 26 }, (_, i) => statOf(stats.itemLevel[`${levelOption - levelOffset}#${baseIlvl + 5 * i}`], stat));
		// Advanced honing runs in two stages (1–20, 21–40); each stage's table is cumulative within it.
		const stage = (l) => statOf(stats.amplification[`${amp}#${l}`]?.stats, stat);
		const a = Array.from({ length: 41 }, (_, l) => stage(Math.min(l, 20)) + (l > 20 ? stage(l) : 0));
		if (h.some((v) => !v) || !a[40]) throw new Error(`missing honing data for ${slot}`);
		honing[slot] = { honing: h, advanced: a };
	}
	return honing;
}
const honing = honingTable(BASE_ILVL, 0);
const aegirHoning = honingTable(1590, 1000000);
fs.writeFileSync(
	'src/lib/upgrade-planner/honing-data.ts',
	`${header('T4 Aegir and Serca gear; armor values are main stat, weapon values are Weapon Power.')}// honing[h] = stat at +h; advanced[l] = cumulative stat from advanced honing level l.

export const HONING_SLOTS = ${JSON.stringify(Object.keys(SLOTS))} as const;
export type HoningSlot = (typeof HONING_SLOTS)[number];

export const HONING_TABLE: Record<HoningSlot, { honing: number[]; advanced: number[] }> = ${JSON.stringify(honing, null, '\t')};

export const AEGIR_HONING_TABLE: typeof HONING_TABLE = ${JSON.stringify(aegirHoning, null, '\t')};
`
);

// ------------------------------------------------------------------------------------------- items

// Weapons/armor (T4 only), accessories, bracelets, ability stones, orbs, T3/T4 gems and astrogems.
// Ark grid cores are left out: thousands of ids share six icons, which iconForCore() derives instead.
const wanted = ([id, v]) =>
	(v.tier === 4 && v.type === 1 && v.category >= 10101 && v.category <= 10501) ||
	(v.category === 50300 && /^650[234]/.test(id)) || // regular T3/T4 gems; 6509xxxx are event variants
	v.category === 50500;
const itemMap = {};
for (const [id, v] of Object.entries(items).filter(wanted)) itemMap[id] = [v.icon, v.name, v.grade];

// Astrogem kinds: base willpower and the four options each kind can roll. Keyed by the item's arkGem id.
const KIND_NAMES = ['Stability', 'Solidity', 'Immutability', 'Corrosion', 'Distortion', 'Destruction'];
const astrogemKinds = {};
for (const [id, v] of Object.entries(stats.arkGridGems))
	astrogemKinds[id] = { name: KIND_NAMES[v.type], attr: v.attr === 0 ? 'order' : 'chaos', willpower: v.points, options: v.options.map((o) => o.id) };
const astrogemItems = {};
for (const [id, v] of Object.entries(items)) if (v.category === 50500 && v.arkGem) astrogemItems[id] = v.arkGem;

// ------------------------------------------------------------------------------------------- engravings

const engravingIcons = {};
for (const [id, v] of Object.entries(stats.engraving)) if (Number(id) >= 1000 && Number(id) < 2000 && v.icon) engravingIcons[id] = [v.icon, v.name];

// ------------------------------------------------------------------------------------------- skills & gem effects

// Every class skill with a name and icon, so any gem's skill can be named (e.g. Guardian Knight incarnation
// skills). The last field marks regular combat skills (max level 20), offered when reassigning a gem.
const gemSkills = {};
for (const [id, v] of Object.entries(skills))
	if (v.class && v.icon && v.name && Number(id) < 9_000_000)
		gemSkills[id] = [v.name, v.icon, v.class, v.maxLevel === 20 && v.type > 0 && v.category > 0 ? 1 : 0];
// Some gems name a skill group instead of a skill (effect types 34/35: Guardian Knight skills, Brawl King
// Twelve Forms). Groups take their class from their skills and count as regular when any of them is.
const gemSkillGroups = {};
for (const [id, g] of Object.entries(stats.skillGroup ?? {})) {
	const members = (g.skills ?? []).filter((s) => gemSkills[s]);
	if (!g.name || !g.icon || !members.length || gemSkills[id]) continue;
	// Name the forms a group covers when they differ (Rending Finisher (Exploding Finisher)), up to three of them.
	const forms = [...new Set(members.map((m) => gemSkills[m][0]).filter((n) => n !== g.name))].map((n) =>
		n.startsWith(`${g.name}: `) ? n.slice(g.name.length + 2) : n
	);
	const name = forms.length && forms.length <= 3 ? `${g.name} (${forms.join(' / ')})` : g.name;
	gemSkills[id] = [name, g.icon, gemSkills[members[0]][2], members.some((s) => gemSkills[s][3]) ? 1 : 0];
	gemSkillGroups[id] = members.map(Number);
}
// A skill's damage and cooldown gems can name different groups (170008 / 170009 Rending Finisher): alias them to
// one id so they share a row and a damage share. A regular group stands in for its skills in the skill picker.
const gemSkillAlias = {};
const canonical = {};
for (const [id, members] of Object.entries(gemSkillGroups)) {
	const key = `${gemSkills[id][2]}|${gemSkills[id][0]}`;
	if (canonical[key]) {
		gemSkillAlias[id] = Number(canonical[key]);
		gemSkills[id][3] = 0;
		continue;
	}
	canonical[key] = id;
	if (gemSkills[id][3]) for (const m of members) gemSkills[m][3] = 0;
}

// Skill effect per gem level (1–10), in 1/100 %: damage gems raise skill damage, cooldown gems cut cooldown.
const gemEffect = (base) =>
	Array.from({ length: 10 }, (_, i) => {
		const key = Object.keys(stats.itemRandom).find((k) => k.startsWith(`${base + (i + 1) * 10}#`));
		const value = stats.itemRandom[key]?.[0]?.subgroups?.[0]?.options?.[0]?.stats?.[0]?.value;
		if (!value) throw new Error(`missing gem effect for ${base + (i + 1) * 10}`);
		return value;
	});
const gemEffects = {
	T4: { damage: gemEffect(65031000), cooldown: gemEffect(65032000) },
	T3: { damage: gemEffect(65021000), cooldown: gemEffect(65022000) }
};
const gemBaseAttack = Array.from({ length: 10 }, (_, i) => {
	const prefix = `${65031000 + (i + 1) * 10}#`;
	const key = Object.keys(stats.itemStatic).find((k) => k.startsWith(prefix));
	return (stats.itemStatic[key] ?? []).filter((s) => s.type === 2 && s.stat === 150).reduce((sum, s) => sum + s.value, 0) / 100;
});

// ------------------------------------------------------------------------------------------- bracelet effects

const clean = (s) =>
	(s ?? '')
		.replace(/<[^>]+>/g, '')
		.replace(/\{0\}/g, '')
		.replace(/\s*\(Less effective against foes above Lv\. \d+\)/g, '')
		.replace(/\s+/g, ' ')
		.trim();
const bracelet = stats.battlePoint['1']
	.filter((e) => e.type === 20)
	.map(({ values: [kind, id, value] }) => {
		// Effects come in families of four grades with consecutive ids; grade 0 is the best.
		const family = kind === 3 ? `a${Math.floor(id / 10)}` : id >= 605100000 ? `c${Math.floor(id / 10)}` : `c${Math.floor((id - 1) / 4)}`;
		const grade = kind === 3 ? (id % 10) - 1 : id >= 605100000 ? (id % 10) - 1 : (id - 1) % 4;
		const text = clean(kind === 3 ? stats.engraving[id]?.desc?.[0] : stats.combatEffectDesc[id]);
		return { key: `${kind}:${id}`, value, family, grade, text, t4: kind === 3 || id >= 605100000 };
	});

// ------------------------------------------------------------------------------------------- event gems

// Event gems (6509xxxx, e.g. "Lv. 7 Blazing Gem") don't encode tier / kind / level in their id; each one names
// the regular gem it behaves as.
const gemRegular = {};
for (const [id, v] of Object.entries(items)) if (/^6509\d{4}$/.test(id) && v.gem?.random) gemRegular[id] = v.gem.random;

// ------------------------------------------------------------------------------------------- ark grid cores

// Core item id → option name ("Chaos Moon Core: Echoing Brand" → "Echoing Brand"), one entry per id shape/option
// (grade digit dropped) so the simulator can name a core after a grade swap too.
const coreNames = {};
for (const [id, v] of Object.entries(items))
	if (/^673\d{6}$/.test(id) && v.name) coreNames[id.slice(0, 8)] = v.name.replace(/^.*Core: /, '');

// ------------------------------------------------------------------------------------------- support battle points

// The game scores supports with its own battle point table (role 2): Buff Power from the "attack" parts and
// Shield & Heal Power from the "defense" parts. Missing values are 0.
const sbp = stats.battlePoint['2'];
const ofType = (t) => sbp.filter((e) => e.type === t).map((e) => e.values);
const one = (t) => ofType(t)[0]?.[0] ?? 0;
const byLevel = (rows, key) => {
	const out = {};
	for (const [id, level, value = 0] of rows) (out[id] ??= [])[level - 1] = value;
	return key ? out[key] : out;
};
// Engravings: code = stone × 20 + 9 + relic book step (5 steps); same [stone][books] layout as the dealer table.
const engravingTables = (t) => {
	const out = {};
	for (const [id, code, value = 0] of ofType(t)) {
		const stone = Math.floor(code / 20);
		const col = (code % 20) - 9;
		if (col < 0 || col > 4 || stone > 4) continue;
		((out[id] ??= [])[stone] ??= [])[col] = value;
	}
	return out;
};
const supportBracelet = [...ofType(20).map((v) => [...v, 'attack']), ...ofType(21).map((v) => [...v, 'defense'])].map(
	([kind, id, value, side]) => {
		const family = kind === 3 ? `a${Math.floor(id / 10)}` : id >= 605100000 ? `c${Math.floor(id / 10)}` : `c${Math.floor((id - 1) / 4)}`;
		const grade = kind === 3 ? (id % 10) - 1 : id >= 605100000 ? (id % 10) - 1 : (id - 1) % 4;
		const text = clean(kind === 3 ? stats.engraving[id]?.desc?.[0] : stats.combatEffectDesc[id]);
		return { key: `${kind}:${id}`, value, side, family, grade, text, t4: kind === 3 || id >= 605100000 };
	}
);
const supportData = {
	baseAttack: one(1),
	baseHealth: one(2),
	evolutionKarmaPerRank: one(8),
	gems: { T4: byLevel(ofType(22), 4), T3: byLevel(ofType(22), 3) },
	engravings: engravingTables(10),
	engravingsDefense: engravingTables(11),
	accessory: ofType(15),
	accessoryDefense: ofType(16),
	accessoryEffect: ofType(17),
	braceletStat: ofType(19),
	combatStat: Object.fromEntries(ofType(26)),
	cores: byLevel(ofType(29)),
	coresDefense: byLevel(ofType(30)),
	weaponCores: Object.fromEntries(Object.entries(items).filter(([, item]) => item.arkCore?.group === 673121003).map(([id, item]) => [id,
		item.arkCore.bonuses.map(({ points, id: bonus }) => [points,
			...[151, 152].map((stat) => (stats.arkGridCoreOptions[bonus]?.stats ?? []).filter((s) => s.type === 2 && s.stat === stat).reduce((sum, s) => sum + s.value, 0))])
	])),
	astrogem: byLevel(ofType(31))
};
fs.writeFileSync(
	'src/lib/upgrade-planner/support-data.ts',
	`${header("Support (role 2) battle point table from the game data; see support.ts.")}
/** Support battle points: Buff Power parts and Shield & Heal Power ("Defense") parts. */
export const SUPPORT_BP = ${JSON.stringify(supportData)};

/** Bracelet effects as the support table scores them ("attack" = Buff Power, "defense" = Shield & Heal Power). */
export const SUPPORT_BRACELET_EFFECTS: { key: string; value: number; side: 'attack' | 'defense'; family: string; grade: number; text: string; t4: boolean }[] = ${JSON.stringify(supportBracelet)};
`
);

fs.writeFileSync(
	'src/lib/upgrade-planner/game-data.ts',
	`${header('Icons are names on the official game CDN; see iconUrl().')}
/** item id → [icon, name, grade] for gear, accessories, bracelets, stones, gems and astrogems. */
export const ITEMS: Record<number, [icon: string, name: string, grade: number]> = ${JSON.stringify(itemMap)};

/** Astrogem kind (by the item's arkGem id): base willpower and the options it can roll. */
export const ASTROGEM_KINDS: Record<number, { name: string; attr: 'order' | 'chaos'; willpower: number; options: number[] }> = ${JSON.stringify(astrogemKinds)};

/** Astrogem item id → arkGem kind id. */
export const ASTROGEM_ITEMS: Record<number, number> = ${JSON.stringify(astrogemItems)};

/** Skill id → [name, icon, class key, regular combat skill (1) or not (0)] for every class skill. */
export const GEM_SKILLS: Record<number, [name: string, icon: string, classKey: string, regular: 0 | 1]> = ${JSON.stringify(gemSkills)};

/** Skill group id → its skills, for gems that name a group (shares from logs add up over the group). */
export const GEM_SKILL_GROUPS: Record<number, number[]> = ${JSON.stringify(gemSkillGroups)};

/** Duplicate skill group id → the group id used for it (same class and name). */
export const GEM_SKILL_ALIAS: Record<number, number> = ${JSON.stringify(gemSkillAlias)};

/** Gem skill effect by level (index 0 = Lv. 1), in 1/100 %: damage % for damage gems, cooldown % for cooldown gems. */
export const GEM_EFFECTS: Record<'T4' | 'T3', { damage: number[]; cooldown: number[] }> = ${JSON.stringify(gemEffects)};

/** T4 gem base Attack Power percentage by level (1–10), separate from gem battle points. */
export const GEM_BASE_ATTACK: number[] = ${JSON.stringify(gemBaseAttack)};

/** Event gem id → the regular gem id it behaves as (same tier, kind and level). */
export const GEM_REGULAR: Record<number, number> = ${JSON.stringify(gemRegular)};

/** Core item id without its grade digit (first 8 digits) → option name, e.g. 67311300 → "Echoing Brand". */
export const CORE_NAMES: Record<string, string> = ${JSON.stringify(coreNames)};

/** lostark.bible engraving id → [icon, name]. */
export const ENGRAVING_ICONS: Record<number, [icon: string, name: string]> = ${JSON.stringify(engravingIcons)};

export interface BraceletEffect {
	/** "3:<ability id>" or "4:<combat effect id>", matching bible's bracelet stat type + index. */
	key: string;
	/** Battle points the game assigns this effect. */
	value: number;
	family: string;
	/** 0 = best of its family's four grades. */
	grade: number;
	text: string;
	/** Rolls on current T4 bracelets (the rest are older effects that still carry battle points). */
	t4: boolean;
}

export const BRACELET_EFFECTS: BraceletEffect[] = [
${bracelet.map((b) => `\t${JSON.stringify(b)}`).join(',\n')}
];
`
);

console.log(
	`items ${Object.keys(itemMap).length}, engravings ${Object.keys(engravingIcons).length}, bracelet effects ${bracelet.length}, ` +
		`gem skills ${Object.keys(gemSkills).length}, gem effects ${JSON.stringify(gemEffects)}`
);

