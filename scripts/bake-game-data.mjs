// Bakes the small slices of the game's tables the simulator needs, from Maxroll's planner data feed
// (https://assets-ng.maxroll.gg/laplanner/game/{stats,items}.json). Run once per game patch:
//   node scripts/bake-game-data.mjs
// Writes:
//   src/lib/upgrade-planner/honing-data.ts  main stat / Weapon Power by honing level (T4 1675 gear)
//   src/lib/upgrade-planner/game-data.ts    item icons + names, engraving icons, bracelet effect catalog

import fs from 'node:fs';

async function cached(name) {
	const file = `cache/maxroll-${name}.json`;
	if (!fs.existsSync(file)) {
		fs.mkdirSync('cache', { recursive: true });
		const res = await fetch(`https://assets-ng.maxroll.gg/laplanner/game/${name}.json`);
		if (!res.ok) throw new Error(`${name}.json: ${res.status}`);
		fs.writeFileSync(file, await res.text());
	}
	return JSON.parse(fs.readFileSync(file, 'utf8'));
}

const stats = await cached('stats');
const items = await cached('items');
const statOf = (list, stat) => (list ?? []).filter((s) => s.stat === stat).reduce((a, s) => a + s.value, 0);
const header = (what) => `// Generated by scripts/bake-game-data.mjs from the game's tables (via Maxroll's planner feed).
// Do not edit by hand. ${what}
`;

// ------------------------------------------------------------------------------------------- honing

const BASE_ILVL = 1675;
// levelOption ids (item table) and advanced-honing groups per slot; DEX variants, STR/INT are identical.
const SLOTS = {
	weapon: { levelOption: 12159000, amp: 1010, stat: 151 },
	head: { levelOption: 12159021, amp: 2110, stat: 4 },
	upper_body: { levelOption: 12159022, amp: 3110, stat: 4 },
	lower_body: { levelOption: 12159023, amp: 4110, stat: 4 },
	hand: { levelOption: 12159024, amp: 5110, stat: 4 },
	shoulder: { levelOption: 12159025, amp: 6110, stat: 4 }
};
const honing = {};
for (const [slot, { levelOption, amp, stat }] of Object.entries(SLOTS)) {
	const h = Array.from({ length: 26 }, (_, i) => statOf(stats.itemLevel[`${levelOption}#${BASE_ILVL + 5 * i}`], stat));
	// Advanced honing runs in two stages (1–20, 21–40); each stage's table is cumulative within it.
	const stage = (l) => statOf(stats.amplification[`${amp}#${l}`]?.stats, stat);
	const a = Array.from({ length: 41 }, (_, l) => stage(Math.min(l, 20)) + (l > 20 ? stage(l) : 0));
	if (h.some((v) => !v) || !a[40]) throw new Error(`missing honing data for ${slot}`);
	honing[slot] = { honing: h, advanced: a };
}
fs.writeFileSync(
	'src/lib/upgrade-planner/honing-data.ts',
	`${header('T4 1675 "Destined Tremor" gear; armor values are main stat, weapon values are Weapon Power.')}// honing[h] = stat at +h; advanced[l] = cumulative stat from advanced honing level l.

export const HONING_SLOTS = ${JSON.stringify(Object.keys(SLOTS))} as const;
export type HoningSlot = (typeof HONING_SLOTS)[number];

export const HONING_TABLE: Record<HoningSlot, { honing: number[]; advanced: number[] }> = ${JSON.stringify(honing, null, '\t')};
`
);

// ------------------------------------------------------------------------------------------- items

// Weapons/armor (T4 only), accessories, bracelets, ability stones, orbs, T3/T4 gems and astrogems.
// Ark grid cores are left out: thousands of ids share six icons, which iconForCore() derives instead.
const wanted = ([id, v]) =>
	(v.tier === 4 && v.type === 1 && v.category >= 10101 && v.category <= 10501) ||
	(v.category === 50300 && /^650[234]/.test(id)) || // regular T3/T4 gems; 6509xxxx are event variants
	v.category === 50500;
const itemMap = {};
for (const [id, v] of Object.entries(items).filter(wanted)) itemMap[id] = [v.icon, v.name, v.grade];

// Astrogem kinds: base willpower and the four options each kind can roll. Keyed by the item's arkGem id.
const KIND_NAMES = ['Stability', 'Solidity', 'Immutability', 'Corrosion', 'Distortion', 'Destruction'];
const astrogemKinds = {};
for (const [id, v] of Object.entries(stats.arkGridGems))
	astrogemKinds[id] = { name: KIND_NAMES[v.type], attr: v.attr === 0 ? 'order' : 'chaos', willpower: v.points, options: v.options.map((o) => o.id) };
const astrogemItems = {};
for (const [id, v] of Object.entries(items)) if (v.category === 50500 && v.arkGem) astrogemItems[id] = v.arkGem;

// ------------------------------------------------------------------------------------------- engravings

const engravingIcons = {};
for (const [id, v] of Object.entries(stats.engraving)) if (Number(id) >= 1000 && Number(id) < 2000 && v.icon) engravingIcons[id] = [v.icon, v.name];

// ------------------------------------------------------------------------------------------- bracelet effects

const clean = (s) =>
	(s ?? '')
		.replace(/<[^>]+>/g, '')
		.replace(/\{0\}/g, '')
		.replace(/\s*\(Less effective against foes above Lv\. \d+\)/g, '')
		.replace(/\s+/g, ' ')
		.trim();
const bracelet = stats.battlePoint['1']
	.filter((e) => e.type === 20)
	.map(({ values: [kind, id, value] }) => {
		// Effects come in families of four grades with consecutive ids; grade 0 is the best.
		const family = kind === 3 ? `a${Math.floor(id / 10)}` : id >= 605100000 ? `c${Math.floor(id / 10)}` : `c${Math.floor((id - 1) / 4)}`;
		const grade = kind === 3 ? (id % 10) - 1 : id >= 605100000 ? (id % 10) - 1 : (id - 1) % 4;
		const text = clean(kind === 3 ? stats.engraving[id]?.desc?.[0] : stats.combatEffectDesc[id]);
		return { key: `${kind}:${id}`, value, family, grade, text, t4: kind === 3 || id >= 605100000 };
	});

fs.writeFileSync(
	'src/lib/upgrade-planner/game-data.ts',
	`${header('Icons are names on the official game CDN; see iconUrl().')}
/** item id → [icon, name, grade] for gear, accessories, bracelets, stones, gems and astrogems. */
export const ITEMS: Record<number, [icon: string, name: string, grade: number]> = ${JSON.stringify(itemMap)};

/** Astrogem kind (by the item's arkGem id): base willpower and the options it can roll. */
export const ASTROGEM_KINDS: Record<number, { name: string; attr: 'order' | 'chaos'; willpower: number; options: number[] }> = ${JSON.stringify(astrogemKinds)};

/** Astrogem item id → arkGem kind id. */
export const ASTROGEM_ITEMS: Record<number, number> = ${JSON.stringify(astrogemItems)};

/** lostark.bible engraving id → [icon, name]. */
export const ENGRAVING_ICONS: Record<number, [icon: string, name: string]> = ${JSON.stringify(engravingIcons)};

export interface BraceletEffect {
	/** "3:<ability id>" or "4:<combat effect id>", matching bible's bracelet stat type + index. */
	key: string;
	/** Battle points the game assigns this effect. */
	value: number;
	family: string;
	/** 0 = best of its family's four grades. */
	grade: number;
	text: string;
	/** Rolls on current T4 bracelets (the rest are older effects that still carry battle points). */
	t4: boolean;
}

export const BRACELET_EFFECTS: BraceletEffect[] = [
${bracelet.map((b) => `\t${JSON.stringify(b)}`).join(',\n')}
];
`
);

console.log(`items ${Object.keys(itemMap).length}, engravings ${Object.keys(engravingIcons).length}, bracelet effects ${bracelet.length}`);
