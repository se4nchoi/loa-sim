// Run after bake-game-data.mjs. Uses the same cached Maxroll game tables.
import fs from 'node:fs';
const read = (name) => JSON.parse(fs.readFileSync(`cache/maxroll-${name}.json`, 'utf8'));
const items = read('items');
const stats = read('stats');
const weapons = Object.fromEntries(Object.entries(items)
	.filter(([, v]) => v.type === 1 && v.grade === 7)
	.map(([id, v]) => [id, { infusion: Math.floor(Number(id) / 1000) % 10 - 1, icon: v.icon, name: v.name }]));
const power = (rows) => rows?.find((s) => s.stat === 151)?.value ?? 0;
const stages = [21110000, 22110000, 23110000, 24110000].map((group) => {
	const rows = Object.entries(stats.itemQuality).filter(([key]) => key.startsWith(`${group}#`));
	return Object.fromEntries(rows.map(([key, v]) => {
		const level = Number(key.split('#')[1]) - 100;
		const ilvl = 1100 + v.level;
		const weaponPower = power(stats.itemLevel[`${group}#${ilvl}`]);
		if (!weaponPower) throw new Error(`Missing Sidereal stat row ${group}#${ilvl}`);
		return [level, { ilvl, weaponPower }];
	}));
});
const advanced = [1000, 1010].map((group) => Array.from({ length: group === 1000 ? 21 : 41 }, (_, level) =>
	power(stats.amplification[`${group}#${Math.min(level, 20)}`]?.stats)
	+ (level > 20 ? power(stats.amplification[`${group}#${level}`]?.stats) : 0)));
fs.writeFileSync('src/lib/upgrade-planner/sidereal-data.ts', `// Generated by scripts/bake-sidereal-data.mjs from Maxroll's game tables.
export const SIDEREAL_ITEMS: Record<number, { infusion: number; icon: string; name: string }> = ${JSON.stringify(weapons)};
export const SIDEREAL_STAGES: Record<number, { ilvl: number; weaponPower: number }>[] = ${JSON.stringify(stages)};
export const SIDEREAL_ADVANCED: number[][] = ${JSON.stringify(advanced)};
`);
