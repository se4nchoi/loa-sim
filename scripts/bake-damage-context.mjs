// Small static damage-stat slices, not CP weights. node scripts/bake-damage-context.mjs
import fs from 'node:fs';
const stats = JSON.parse(fs.readFileSync('cache/maxroll-stats.json', 'utf8'));
const wanted = new Set([45, 49, 50, 74, 76]);
const passives = {};
for (const [id, p] of Object.entries(stats.arkPassives)) {
	passives[id] = { name: p.name,
		...(/(?<!Ally )Atk\. Power [+-]/.test(p.desc.replace(/<[^>]*>/g, '')) && !(p.stats ?? []).some(s => s.type === 2 && s.stat === 49) ? { unresolvedAttack: true } : {}),
		levels: Array.from({ length: p.levels }, (_, index) => {
		const level = index + 1;
		return (p.stats ?? []).filter(s => s.type === 2 && wanted.has(s.stat)).map(s => ({
			stat: s.stat, value: typeof s.value === 'number' ? s.value : s.value[level]
		}));
	}) };
}
const cards = Object.values(stats.cardSets).filter(set => set.type === 2 && set.effects.some(e => e.stats?.some(s => s.type === 2 && wanted.has(s.stat))))
	.map(set => ({ name: set.name, cards: set.cards, effects: set.effects.map(e => ({ count: e.count, levelSum: e.levelSum,
		stats: (e.stats ?? []).filter(s => s.type === 2 && wanted.has(s.stat)).map(s => ({ stat: s.stat, value: s.value })) })) }));
// Master is a buff rather than a direct stat addon. Keep its explicit cap and amounts as an assumption.
const masterText = stats.arkPassives[1032200].desc.replace(/<[^>]*>/g, '');
const master = { stacks: Number(masterText.match(/Max (\d+) stacks/)?.[1]),
	additionalDamage: Number(masterText.match(/Additional Damage \+([\d.]+)%/)?.[1]),
	critRate: Number(masterText.match(/Crit Rate \+([\d.]+)%/)?.[1]) };
if (!Object.values(master).every(n => Number.isFinite(n) && n > 0)) throw new Error('Master schema changed');
const engravingAdditional = Object.fromEntries(Object.entries(stats.engraving).filter(([, e]) => e.season === 2)
	.map(([id, e]) => [id, e.desc.some(text => /Additional Damage/i.test(text ?? ''))]));
const engravingStats = {};
for (const [id, e] of Object.entries(stats.engraving).filter(([, e]) => e.season === 2)) {
	engravingStats[id] = e.desc.map(raw => {
		if (!raw) return null;
		const text = raw.replace(/<[^>]*>/g, '');
		const stacks = Number(text.match(/Stacks up to (\d+) times/)?.[1] ?? 1);
		const read = (label, reverse = false) => {
			const m = text.match(new RegExp(`${label} ([+-][\\d.]+)%`)) ?? (reverse ? text.match(new RegExp(`([+-][\\d.]+)% ${label}`)) : null);
			return m ? Number(m[1]) : new RegExp(label, 'i').test(text) ? null : 0;
		};
		const attack = read('Atk\\. Power');
		return { attackPowerPct: attack === null ? null : Math.round(attack * stacks * 1e8) / 1e8,
			critDamage: read('Crit Damage', true), critRate: read('Crit Rate'), stacks };
	});
}
fs.writeFileSync('src/lib/upgrade-planner/damage-context-data.ts', `// Generated by scripts/bake-damage-context.mjs from Maxroll's game tables. Do not edit by hand.
export const PASSIVE_DAMAGE_STATS: Readonly<Record<number, {name: string; unresolvedAttack?: boolean; levels: {stat: number; value: number}[][]}>> = ${JSON.stringify(passives)};
export const CARD_DAMAGE_STATS = ${JSON.stringify(cards)};
export const MASTER_STATS = ${JSON.stringify(master)};
export const ENGRAVING_ADDITIONAL_DAMAGE: Readonly<Record<number, boolean>> = ${JSON.stringify(engravingAdditional)};
export const ENGRAVING_DAMAGE_STATS: Readonly<Record<number, ({attackPowerPct: number | null; critDamage: number | null; critRate: number | null; stacks: number} | null)[]>> = ${JSON.stringify(engravingStats)};
`);
console.log(`${Object.keys(passives).length} passive definitions, ${cards.length} equipped card sets`);
const evolutionCaps = {};
for (const [id, metric] of [[1040100, 'bluntThornEfficiency'], [1040200, 'supersonicBreakthroughEfficiency']]) {
	const p = stats.arkPassives[id];
	evolutionCaps[id] = { metric, caps: Array.from({length: p.levels}, (_, index) => {
		const level = index + 1;
		const description = p.desc.replace(/<[^>]*>/g, '').replace(/\{\d+:([^}]+)\}/g, (_, choices) => choices.split('|')[index]);
		const totalCap = Number(description.match(/capped at (?:\{[^}]+\})?([\d.]+)%/)?.[1]);
		const base = (p.stats ?? []).filter(s => s.type === 2 && s.stat === 45).reduce((sum, s) => sum + (typeof s.value === 'number' ? s.value : s.value[level]) / 100, 0);
		const cap = totalCap - base;
		if (!Number.isFinite(cap) || cap <= 0) throw new Error(`Unsupported evolution cap ${id}:${level}`);
		return cap;
	}) };
}
fs.writeFileSync('src/lib/logs/evolution-caps.ts', `// Generated by scripts/bake-damage-context.mjs from Maxroll's game tables. Caps in percentage points.
export const EVOLUTION_CAPS: Readonly<Record<number, {metric: string; caps: number[]}>> = ${JSON.stringify(evolutionCaps)};
`);
