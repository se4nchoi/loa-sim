// Bakes what the support sim reads off the Ark Grid into src/lib/upgrade-planner/support-buffs.ts:
//   - the support astrogem options' stat value per total level (Ally Damage Enhancement, Brand Power, Ally Atk. Power
//     Enhancement; hundredths of a percent, like accessory lines), from the Maxroll feed cache (cache/maxroll-stats.json).
//     The CP tables hold battle points, not these values;
//   - support Order cores' unconditional Ally Atk. Power / Ally Damage Enhancement lines by core id and points, from
//     src/lib/upgrade-planner/order-cores.ts (bake-order-cores.mjs). Lines that need a Destiny effect or name one skill
//     ("Destiny: …", "Paint: Dragon Engraving Party Damage Enhancement") aren't baked: the logs don't say when they held.
//   node scripts/bake-support-buffs.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const options = JSON.parse(readFileSync('cache/maxroll-stats.json', 'utf8')).arkGridGemOptions;
const astrogems = {};
for (const id of [2011, 2012, 2013]) {
	const values = [];
	for (let level = 1; options[`${id}#${level}`]; level++) values.push(options[`${id}#${level}`].stat.value);
	astrogems[id] = values;
}

const src = readFileSync('src/lib/upgrade-planner/order-cores.ts', 'utf8').split('\n');
const grab = (name) => JSON.parse(src.find((l) => l.startsWith(`export const ${name}`)).replace(/^[^=]*= /, '').replace(/;$/, ''));
const cores = grab('ORDER_CORES'), effects = grab('ORDER_CORE_EFFECTS');
const SUPPORTS = new Set(['bard', 'holyknight', 'holyknight_female', 'yinyangshi']);
const PLAIN = /^(?:Party|Ally) (Atk\.|Attack\.) Power Enhancement [Ee]ffect \+([\d.]+)%\.?$|^(?:Party|Ally) Damage Enhancement [Ee]ffect \+([\d.]+)%\.?$/;
const coreLines = {};
for (const [id, c] of Object.entries(cores)) {
	if (!SUPPORTS.has(c.cls)) continue;
	const lines = [];
	for (const [points, option] of c.bonuses) {
		const text = (effects[option] ?? []).map((e) => e.text ?? '').join(' ').trim();
		const m = text.match(PLAIN);
		if (m) lines.push([points, Number(m[2] ?? 0), Number(m[3] ?? 0)]);
	}
	if (lines.length) coreLines[id] = lines;
}

writeFileSync('src/lib/upgrade-planner/support-buffs.ts', `// Generated by scripts/bake-support-buffs.mjs. Do not edit by hand.
// Support astrogem options: stat value (hundredths of a percent) at each total level from 1, by option id:
// 2011 Ally Damage Enhancement, 2012 Brand Power, 2013 Ally Atk. Power Enhancement.
export const SUPPORT_ASTROGEM_VALUES: Record<number, number[]> = ${JSON.stringify(astrogems)};

// Support Order cores' unconditional lines: [points needed, Ally Atk. Power Enhancement %, Ally Damage Enhancement %].
export const SUPPORT_CORE_LINES: Record<number, [points: number, allyAtk: number, allyDmg: number][]> = ${JSON.stringify(coreLines)};
`);
console.log(Object.keys(coreLines).length, 'support cores with lines; e.g.', JSON.stringify(Object.entries(coreLines).slice(0, 2)));
